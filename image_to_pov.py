"""Convert an image into radial POV column data for an 8-LED blade.

Usage:
    python image_to_pov.py my_logo.png --columns 360 --out ../firmware/pov_fan/frame.h

Each column = one angular slice of the rotation. Each byte holds the
state of the 8 LEDs for that slice (bit 0 = LED nearest the hub).
"""
import argparse
import math
from PIL import Image


def convert(path, columns=360, leds=8, threshold=128, invert=False):
    size = 2 * leds
    img = Image.open(path).convert("L").resize((size, size))
    px = img.load()
    c = size / 2.0
    out = []
    for k in range(columns):
        a = 2 * math.pi * k / columns
        byte = 0
        for i in range(leds):
            r = i + 0.5
            x = min(size - 1, max(0, int(c + r * math.cos(a))))
            y = min(size - 1, max(0, int(c - r * math.sin(a))))
            on = px[x, y] >= threshold
            if invert:
                on = not on
            if on:
                byte |= 1 << i
        out.append(byte)
    return out


def write_header(data, path):
    with open(path, "w") as f:
        f.write("// Auto-generated by software/image_to_pov.py\n#pragma once\n")
        f.write("#include <avr/pgmspace.h>\n")
        f.write("#define NUM_COLUMNS %d\n" % len(data))
        f.write("const uint8_t FRAME[NUM_COLUMNS] PROGMEM = {\n")
        for i in range(0, len(data), 12):
            f.write("  " + ", ".join("0x%02X" % b for b in data[i:i + 12]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("image")
    p.add_argument("--columns", type=int, default=360)
    p.add_argument("--leds", type=int, default=8)
    p.add_argument("--threshold", type=int, default=128)
    p.add_argument("--invert", action="store_true")
    p.add_argument("--out", default="frame.h")
    a = p.parse_args()
    write_header(convert(a.image, a.columns, a.leds, a.threshold, a.invert), a.out)
    print("Wrote", a.out)
